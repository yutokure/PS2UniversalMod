"""Write reports/SUIKODEN5_STATE_DIFF.md: what the five savestates say about the camera.

    python analysis/suikoden5/summarize.py

Reads the extracted eeMemory.bin of each state (see diff_states.py, scripts/ps2lab/sstate_zip.py)
and prints only numbers: addresses, counts and camera values.  No memory content is copied.
"""
from __future__ import annotations

import math
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from diff_states import NAMES, changed_words, load  # noqa: E402

OUT = Path(__file__).resolve().parents[2] / "reports" / "SUIKODEN5_STATE_DIFF.md"
CAM_CTL = 0x129D7D8
LABELS = {"S0": "base", "S1": "base_only_wait", "S2": "zoom only (R1 stage 2)",
          "S3": "character and camera moved", "S4": "character little, camera pitch much"}


def main() -> None:
    mem = {k: load(k) for k in NAMES}
    f = {k: v.view("<f4") for k, v in mem.items()}
    noise = set(changed_words(mem["S0"], mem["S1"]).tolist())
    lines = ["# Suikoden V savestate differences (S0..S4)", "",
             "Generated by `analysis/suikoden5/summarize.py` from the extracted EE RAM of the five states.", "",
             "## Changed 32-bit words", "",
             "| pair | changed words | not in the wait-only noise | of those, plausible floats |",
             "|---|---|---|---|"]
    for a, b in (("S0", "S1"), ("S0", "S2"), ("S0", "S3"), ("S0", "S4"), ("S3", "S4")):
        idx = changed_words(mem[a], mem[b])
        clean = [i for i in idx.tolist() if i not in noise]
        nice = [i for i in clean if i * 4 >= 0x100000 and np.isfinite(f[a][i]) and np.isfinite(f[b][i])
                and 1e-3 < abs(f[a][i]) < 1e6 and 1e-3 < abs(f[b][i]) < 1e6]
        lines.append(f"| {a} <-> {b} | {len(idx)} | {len(clean) if (a, b) != ('S0', 'S1') else '-'} | "
                     f"{len(nice) if (a, b) != ('S0', 'S1') else '-'} |")
    lines += ["", "S0<->S1 is the time-only noise (timers, counters). S0<->S2 isolates the zoom; "
              "S0<->S4 isolates the camera when the character barely moved.", "",
              "## Camera values per state", "",
              "| state | meaning | distance | pitch | yaw | FOV | focus T (x, y, z) | eye P (x, y, z) |",
              "|---|---|---|---|---|---|---|---|"]
    for k in NAMES:
        g = f[k]
        w = lambda a: float(g[a // 4])
        T = [w(0x82DBDC), w(0x82DBE0), w(0x82DBE4)]
        P = [w(0x82DBE8), w(0x82DBEC), w(0x82DBF0)]
        lines.append(f"| {k} | {LABELS[k]} | {w(0x82DC00):.1f} | {w(0x82DBF4):.1f} | {w(0x82DBF8):.1f} | "
                     f"{w(0x82DC4C):.1f} | ({T[0]:.1f}, {T[1]:.1f}, {T[2]:.1f}) | ({P[0]:.1f}, {P[1]:.1f}, {P[2]:.1f}) |")
    lines += ["", "Check: the eye minus the focus has length = distance and the direction",
              "`(cos p sin(yaw+180), sin p, cos p cos(yaw+180))`:", "",
              "| state | |P-T| | predicted offset | measured offset |", "|---|---|---|---|"]
    for k in NAMES:
        g = f[k]
        w = lambda a: float(g[a // 4])
        d, p, y = w(0x82DC00), math.radians(w(0x82DBF4)), math.radians(w(0x82DBF8) + 180.0)
        pred = [d * math.cos(p) * math.sin(y), d * math.sin(p), d * math.cos(p) * math.cos(y)]
        meas = [w(0x82DBE8 + 4 * i) - w(0x82DBDC + 4 * i) for i in range(3)]
        lines.append(f"| {k} | {math.dist(meas, [0, 0, 0]):.1f} | "
                     f"({pred[0]:.1f}, {pred[1]:.1f}, {pred[2]:.1f}) | ({meas[0]:.1f}, {meas[1]:.1f}, {meas[2]:.1f}) |")
    lines += ["", "## Camera control object (0x%08X)" % CAM_CTL, "",
              "| state | +0x1C distance | +0x20 pitch | +0x24 yaw | +0x28 FOV | +0x54 zoom stage |", "|---|---|---|---|---|---|"]
    for k in NAMES:
        g = f[k]
        u = mem[k].view("<u4")
        lines.append(f"| {k} | {g[(CAM_CTL + 0x1c) // 4]:.1f} | {g[(CAM_CTL + 0x20) // 4]:.1f} | "
                     f"{g[(CAM_CTL + 0x24) // 4]:.1f} | {g[(CAM_CTL + 0x28) // 4]:.1f} | "
                     f"{int(u[(CAM_CTL + 0x54) // 4]) & 0xFFFF} |")
    lines += ["", "Zoom (R1) is a pure distance change: 400 -> 300 -> 200 (stages 1..3), pitch, yaw and FOV "
              "unchanged (S0 vs S2). S4 differs from S0 by pitch only (13 -> 40): the game's own camera "
              "zone eases the pitch when the character walks onto the slope (reproduced live, see "
              "docs/SUIKODEN5_CAMERA.md).", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
